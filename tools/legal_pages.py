def main():
    for source, target, fallback, description in PAGES:
        title, updated, body = convert((ROOT / source).read_text())
        toc = "".join(f'<li><a href="#{m.group(1)}">{m.group(2)}</a></li>'
                      for m in re.finditer(r'<h2 id="([^"]+)">(.+?)</h2>', body))
        page = TEMPLATE.format(title=title or fallback, updated=updated, body=body, toc=toc,
                               description=html.escape(description), source=source)
        (ROOT / target).write_text(page)
        print(f"wrote {target}")


if __name__ == "__main__":
    main()
