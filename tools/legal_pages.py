#!/usr/bin/env python3
"""Builds website/privacy.html and website/terms.html from the app's own
PRIVACY_POLICY.md and TERMS_OF_SERVICE.md, so the site and the app can never
say different things. Run from the repo root after editing either document:

    python3 tools/legal_pages.py

The markdown is the small subset those two files use: # and ## headings,
paragraphs, "- " lists whose items wrap onto indented lines, **bold**,
*italic* and [links](url).
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PAGES = [
    ("PRIVACY_POLICY.md", "website/privacy.html", "Privacy Policy",
     "How 808 handles your information: what stays on your phone, what syncs to your own iCloud, and what we can see."),
    ("TERMS_OF_SERVICE.md", "website/terms.html", "Terms of Service",
     "The terms for using the 808 meditation app."),
]


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", text)
    return text


def convert(md):
    lines = md.splitlines()
    out, para, items = [], [], []
    title, updated = "", ""

    def flush_para():
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()

    def flush_list():
        if items:
            out.append("<ul>" + "".join("<li>" + inline(" ".join(i)) + "</li>" for i in items) + "</ul>")
            items.clear()

    for raw in lines:
        line = raw.rstrip()
        if line.startswith("# "):
            title = line[2:].strip()
            continue
        if line.startswith("**Last updated"):
            updated = re.sub(r"\*", "", line).strip()
            continue
        if not line.strip():
            flush_para(); flush_list()
            continue
        if line.startswith("## "):
            flush_para(); flush_list()
            heading = line[3:].strip()
            slug = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
            out.append(f'<h2 id="{slug}">{inline(heading)}</h2>')
            continue
        if line.startswith("- "):
            flush_para()
            items.append([line[2:].strip()])
            continue
        if items and raw.startswith("  "):
            items[-1].append(line.strip())
            continue
        flush_list()
        para.append(line.strip())
    flush_para(); flush_list()
    return title, updated, "\n".join(out)


